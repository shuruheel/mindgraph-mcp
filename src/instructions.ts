/** The instruction sections for a profile and harness, in order. */
export function instructionSections(
  profile: string,
  harness: string,
): InstructionSection[] {
  if (profile === "coding") {
    return [
      { id: "intro", text: INTRO_CODING },
      { id: "coding", text: codingSection(harness) },
      { id: "general", text: CODING_GENERAL },
    ];
  }
  return [
    { id: "intro", text: INTRO_GENERAL },
    { id: "workflow", text: GENERAL_WORKFLOW },
    { id: "retrieval", text: GENERAL_RETRIEVAL },
    { id: "writing", text: GENERAL_WRITING },
  ];
}

export function renderInstructions(
  profile: string,
  harness: string,
): RenderedInstructions {
  let text = "";
  const sections: RenderedInstructions["sections"] = [];
  for (const section of instructionSections(profile, harness)) {
    if (text) text += SEPARATOR;
    const start = text.length;
    text += section.text;
    sections.push({ id: section.id, start, end: text.length });
  }
  return { text, sections };
}

export function buildInstructions(profile: string, harness: string): string {
  return renderInstructions(profile, harness).text;
}
