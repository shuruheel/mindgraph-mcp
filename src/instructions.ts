// Server instructions for the stdio server, built from named sections so the
// length budget is testable by section rather than by matching prose.
//
// Claude Code keeps only the first 4,096 characters of a server's
// instructions (2,048 before v2.1.296). Everything here must fit under that
// with room for the hook-runner version note index.ts may append, and in the
// coding profile the coding guidance must come first: until 0.28 it sat at
// the end of a 6,391-character string and never reached the model.

export interface InstructionSection {
  id: string;
  text: string;
}

export interface RenderedInstructions {
  text: string;
  /** Character offsets of each section in `text` (end is exclusive). */
  sections: Array<{ id: string; start: number; end: number }>;
}

/** Profiles the server distinguishes; any other value renders as "general". */
export const INSTRUCTION_PROFILES = ["general", "coding"] as const;
/** Harness names the installers set in MINDGRAPH_HARNESS ("generic" when unset). */
export const INSTRUCTION_HARNESSES = [
  "generic",
  "claude-code",
  "codex",
  "cursor",
] as const;

const SEPARATOR = "\n\n";

const INTRO_CODING =
  "MindGraph is a persistent knowledge graph that keeps work state, decisions and lessons across sessions and harnesses.";

const INTRO_GENERAL =
  "You have access to a persistent knowledge graph via MindGraph, plus any ontology tools generated by the active schema.";

/** Harnesses whose SessionStart hook injects the resume brief itself. */
const SESSION_BRIEF_HARNESSES = new Set(["claude-code", "codex"]);

function codingSection(harness: string): string {
  const resume = SESSION_BRIEF_HARNESSES.has(harness)
    ? 'If a "MindGraph durable work brief" is already in context, start from it. Otherwise, when resuming or asked what was in progress, call'
    : "Resuming, or asked what was in progress: call";
  return `## Coding sessions

1. ${resume} \`mindgraph_memory\` action \`context\`, mode \`resume\`, before anything else. It reads task-first, lease-aware work state; keyword search cannot answer this ("recent work" matches people named Work). In a multi-repository workspace add \`scope: "workspace"\`.
2. Before your first change this session to existing code (a function, file or route), call \`mindgraph_code\` action \`recall\` with \`code_refs: [{path, symbol}]\`; once per symbol is enough. It finds what is attached to that code by anchor, not keyword. Add \`signature\` to the ref when a name is overloaded; an ambiguous ref returns candidates and never writes.
3. Work that must outlive this session or be visible to other agents goes in \`mindgraph_plan\`; the harness todo list is for this session only. Never track one item in both.
4. After a durable change, write it with \`code_refs\` so it is found from the code later. A decision made: \`mindgraph_commit\` \`open_decision\`, \`add_option\`, then \`resolve_decision\` with the reason in \`summary\`. A correction, a fix that held after failed attempts, an invariant or a blocker with evidence: \`mindgraph_capture\` \`lesson\`. A stated working preference: \`mindgraph_capture\` \`journal\`. Skip routine mechanics, command output, facts the code already shows, guesses, and completion without evidence.
5. Repository scope: a ref's \`path\` routes it to the repository that defines the file; a bare symbol resolves in the current repository, so put \`path\` in the ref or pass \`repo\` to reach a sibling.

The ${harness} adapter supplies invocation_context; omit it.`;
}

